import { createFileRoute, Link } from "@tanstack/react-router";
import { Info } from "lucide-react";
import { useEffect, useState } from "react";
import { Alert, AlertDescription, AlertTitle } from "@/components/ui/alert";
import { Button } from "@/components/ui/button";
import { loadResult, type StoredPrediction } from "@/lib/result-store";

export const Route = createFileRoute("/results")({
  head: () => ({
    meta: [
      { title: "Prediction Result — Diabetes Risk" },
      {
        name: "description",
        content: "Machine-learning diabetes prediction result with risk probability and confidence.",
      },
      { property: "og:title", content: "Prediction Result — Diabetes Risk" },
      {
        property: "og:description",
        content: "Random Forest prediction with probability, confidence and risk banding.",
      },
    ],
  }),
  component: ResultsPage,
});

const riskStyles: Record<string, string> = {
  Low: "bg-success/15 text-success",
  Moderate: "bg-warning/20 text-warning-foreground",
  High: "bg-destructive/15 text-destructive",
};

function ResultsPage() {
  const [result, setResult] = useState<StoredPrediction | null>(null);
  const [ready, setReady] = useState(false);

  useEffect(() => {
    setResult(loadResult());
    setReady(true);
  }, []);

  if (!ready) return <div className="mx-auto max-w-4xl px-4 py-16 sm:px-6" />;

  if (!result) {
    return (
      <div className="mx-auto max-w-2xl px-4 py-20 text-center sm:px-6">
        <h1 className="font-display text-2xl font-semibold">No prediction yet</h1>
        <p className="mt-2 text-muted-foreground">
          Submit patient details on the prediction page to see a result here.
        </p>
        <Button asChild className="mt-6">
          <Link to="/prediction">Go to prediction</Link>
        </Button>
      </div>
    );
  }

  const f = result.features;
  const entered = [
    { label: "Age", value: `${f.age} years` },
    { label: "BMI", value: `${f.bmi} kg/m²` },
    { label: "Physical Activity", value: f.physical_activity },
    { label: "Blood Pressure", value: `${f.blood_pressure} mmHg` },
    { label: "Cholesterol", value: `${f.cholesterol} mg/dL` },
    { label: "Glucose", value: `${f.glucose} mg/dL` },
  ];

  return (
    <div className="mx-auto max-w-4xl px-4 py-12 sm:px-6">
      <p className="text-xs font-semibold uppercase tracking-widest text-muted-foreground">
        Diabetes Prediction
      </p>

      <div className="panel mt-4 p-6 sm:p-8">
        <div className="flex flex-wrap items-start justify-between gap-4">
          <div>
            <p className="text-sm text-muted-foreground">Prediction</p>
            <h1 className="font-display text-4xl font-semibold">{result.prediction}</h1>
          </div>
          <span
            className={`rounded-full px-4 py-1.5 text-sm font-semibold ${riskStyles[result.risk_level]}`}
          >
            {result.risk_level} Risk
          </span>
        </div>

        <div className="mt-8 grid gap-6 sm:grid-cols-2">
          <div>
            <div className="flex justify-between text-sm">
              <span className="text-muted-foreground">Risk probability</span>
              <span className="font-mono font-semibold">{result.risk_percentage}%</span>
            </div>
            <div className="mt-2 h-3 rounded-full bg-secondary">
              <div
                className="h-3 rounded-full bg-primary transition-all"
                style={{ width: `${result.risk_percentage}%` }}
              />
            </div>
            <div className="mt-1 flex justify-between text-[11px] text-muted-foreground">
              <span>Low 0–20%</span>
              <span>Moderate 20–50%</span>
              <span>High 50–100%</span>
            </div>
          </div>
          <div>
            <div className="flex justify-between text-sm">
              <span className="text-muted-foreground">Model confidence</span>
              <span className="font-mono font-semibold">{result.confidence}%</span>
            </div>
            <div className="mt-2 h-3 rounded-full bg-secondary">
              <div
                className="h-3 rounded-full bg-accent transition-all"
                style={{ width: `${result.confidence}%` }}
              />
            </div>
            <p className="mt-1 text-[11px] text-muted-foreground">
              Share of the {result.model.trees} decision trees supporting this class.
            </p>
          </div>
        </div>

        <p className="mt-6 text-sm text-muted-foreground">{result.message}</p>
      </div>

      <Alert className="mt-6">
        <Info className="size-4" />
        <AlertTitle>Educational use only</AlertTitle>
        <AlertDescription>
          This result is generated by a machine-learning model and is intended for
          educational/project purposes only. It should not be considered a medical diagnosis.
        </AlertDescription>
      </Alert>

      <section className="panel mt-6 p-6">
        <h2 className="text-base font-semibold">Health information entered</h2>
        <dl className="mt-4 grid gap-4 sm:grid-cols-3">
          {entered.map((item) => (
            <div key={item.label} className="rounded-lg border border-border bg-surface p-4">
              <dt className="text-xs uppercase text-muted-foreground">{item.label}</dt>
              <dd className="mt-1 font-mono text-sm font-semibold">{item.value}</dd>
            </div>
          ))}
        </dl>
      </section>

      <div className="mt-8 flex flex-wrap gap-3">
        <Button asChild size="lg">
          <Link to="/prediction">Predict Again</Link>
        </Button>
        <Button asChild size="lg" variant="outline">
          <Link to="/model-performance">View model performance</Link>
        </Button>
      </div>
    </div>
  );
}
